import sys
from collections import Counter

def solve():
    n = int(sys.stdin.readline())
    a = list(map(int, sys.stdin.readline().split()))
    
    if n == 0:
        print(0)
        return
    
    cnt = Counter(a)
    freq = sorted(cnt.values(), reverse=True)
    
    # Максимальное число операций
    # k = min(n // 3, (n - max_freq) // 2) - это неверно
    # Правильная формула: k = floor(n / 3), но ограничено суммой двух остальных
    
    # Сортируем частоты по убыванию
    # Пусть f1 >= f2 >= ... >= fm
    # Максимум операций k определяется так:
    # Если f1 > f2 + f3 + ... + fm, то k = f2 + f3 + ... + fm
    # Иначе k = floor(n / 3)
    
    total = n
    f1 = freq[0] if freq else 0
    rest = total - f1
    
    if f1 > rest:
        k = rest
    else:
        k = total // 3
    
    if k == 0:
        # Никаких операций сделать нельзя, все значения хорошие
        good = sorted(cnt.keys())
        print(len(good))
        print(*good)
        return
    
    good = []
    for x in cnt:
        f = cnt[x]
        # Значение x хорошее если:
        # 1) f > k (оно точно останется, т.к. слишком много экземпляров)
        # 2) ИЛИ можно оставить хотя бы один экземпляр x после k операций
        
        # Условие 2: после удаления k троек, содержащих или не содержащих x,
        # должен остаться хотя бы один x.
        # Максимум x-ов, которые можно удалить в k операциях: min(f, k)
        # Останется: f - min(f, k) = max(0, f - k)
        # Но это если мы хотим удалить как можно больше x.
        # Нам нужно чтобы существовала последовательность где x останется.
        
        # Более точное условие:
        # После k операций останется n - 3k элементов.
        # x останется если n - 3k >= 1 и можно сконструировать операции так,
        # чтобы не все x были удалены.
        
        # Если f > k, то даже если в каждой из k операций удалять по одному x,
        # всё равно останется f - k >= 1. Значит x хорошее.
        
        # Если f <= k, то теоретически можно удалить все x. Но вопрос: можно ли
        # сделать k операций НЕ удаляя все x?
        # Для этого нужно чтобы хватило других элементов для заполнения k операций.
        # В каждой операции нужно 2 элемента != x (если мы хотим сохранить x).
        # Нужно: n - f >= 2 * k
        
        if f > k or (n - f >= 2 * k):
            good.append(x)
    
    good.sort()
    print(len(good))
    if good:
        print(*good)

if __name__ == '__main__':
    solve()
