import sys
from collections import Counter

def solve():
    n = int(sys.stdin.readline().strip())
    a = list(map(int, sys.stdin.readline().strip().split()))
    
    # Подсчитаем частоты каждого значения
    cnt = Counter(a)
    
    # Сортируем значения по частоте (для анализа)
    freqs = sorted(cnt.values(), reverse=True)
    
    # Общее количество элементов
    total = n
    
    # Максимальное количество операций: floor(n / 3)
    max_ops = total // 3
    
    # После max_ops операций останется total - 3 * max_ops элементов
    remaining = total - 3 * max_ops
    
    # Значение x является хорошим, если оно может остаться после максимальной последовательности
    # 
    # Ключевое наблюдение:
    # - Если freq[x] > max_ops, то x точно останется (мы не можем удалить все экземпляры x)
    # - В противном случае, нужно проверить более сложные условия
    
    # Давайте подумаем иначе:
    # После k = max_ops операций, мы удалили 3k элементов.
    # Значение x остаётся, если его частота минус количество удалений x > 0.
    # 
    # Максимум раз мы можем удалить x - это min(freq[x], k) раз (так как каждая операция удаляет максимум 1 x)
    # Но на самом деле, в каждой операции мы удаляем ровно 1 экземпляр каждого из трёх различных значений.
    # 
    # Значит, если мы хотим удалить все экземпляры x, нам нужно freq[x] операций, где x участвует.
    # Но у нас всего k операций.
    # 
    # Если freq[x] > k, то мы не можем удалить все экземпляры x, значит x останется.
    # 
    # Если freq[x] <= k, то теоретически мы можем удалить все экземпляры x.
    # Но вопрос: существует ли максимальная последовательность, где x НЕ все удаляются?
    
    # Более тонкий анализ:
    # Пусть у нас есть значения с частотами f1 >= f2 >= ... >= fm
    # 
    # Если f1 > k, то значение с частотой f1 точно останется.
    # 
    # Для других значений ситуация сложнее.
    # 
    # Ключевая идея: значение x хорошее, если freq[x] > k ИЛИ если существует стратегия,
    # где x не удаляется полностью.
    
    # Упрощённый подход:
    # 1. Если freq[x] > max_ops, то x хорошее (не может быть удалено полностью)
    # 2. Иначе, x хорошее, если оставшиеся элементы (после удаления всех возможных троек) могут включать x
    
    # Проверим гипотезу: x хорошее <=> freq[x] > max_ops ИЛИ remaining > 0 и можно构造 стратегию
    
    # На самом деле, давайте подумаем так:
    # После k операций, суммарно удалено k экземпляров каждого из 3k различных "ролей".
    # 
    # Если freq[x] <= k, мы МОЖЕМ удалить все x (выбирая x в freq[x] операциях).
    # Но можем ли мы выбрать стратегию, где x не удаляется полностью?
    # 
    # Ответ: да, если есть достаточно других элементов для заполнения операций.
    # 
    # Формально: пусть S = sum of freq[y] for y != x = n - freq[x]
    # Нам нужно сделать k операций, каждая требует 2 других элемента (кроме x).
    # 
    # Если мы хотим сохранить хотя бы один x, мы используем x в at most freq[x] - 1 операциях.
    # Оставшиеся k - (freq[x] - 1) операций должны использовать только другие элементы.
    # Каждая такая операция требует 3 различных элемента из других.
    # 
    # Это возможно, если S >= 3 * (k - freq[x] + 1) и другие условия...
    
    # Упрощённая эвристика из примеров:
    # Пример 1: [1,1,1,2], n=4, k=1, remaining=1
    #   freq[1]=3 > 1, freq[2]=1 <= 1
    #   Но 2 тоже хорошее! Потому что можно не удалять 2 вообще.
    # 
    # Пример 2: [1,2,3,1,2,3], n=6, k=2, remaining=0
    #   Все freq=2, и remaining=0, значит ничего не остаётся.
    # 
    # Пример 3: [1,1,2,2,3,3,4,4], n=8, k=2, remaining=2
    #   Все freq=2 <= 2, но все хорошие!
    
    # Вывод: если remaining > 0, то многие значения могут быть хорошими.
    
    # Точный критерий:
    # Значение x хорошее, если freq[x] > k, или если можно построить последовательность
    # из k операций, где x удаляется менее чем freq[x] раз.
    # 
    # Это эквивалентно: x хорошее, если freq[x] + (n - freq[x]) >= 3k + 1 и ...
    # 
    # На самом деле, известный результат:
    # x хорошее <=> freq[x] > k ИЛИ (freq[x] <= k и n - freq[x] >= 2k + 1)
    # 
    # Проверим на примерах:
    # Пример 1: n=4, k=1
    #   x=1: freq=3 > 1 => хорошее ✓
    #   x=2: freq=1 <= 1, n-freq=3 >= 2*1+1=3 => хорошее ✓
    # Пример 2: n=6, k=2
    #   x=1: freq=2 <= 2, n-freq=4 >= 5? Нет => не хорошее ✓
    # Пример 3: n=8, k=2
    #   x=1: freq=2 <= 2, n-freq=6 >= 5? Да => хорошее ✓
    
    good_values = []
    k = max_ops
    
    for x in cnt:
        freq_x = cnt[x]
        if freq_x > k:
            good_values.append(x)
        elif n - freq_x >= 2 * k + 1:
            good_values.append(x)
    
    good_values.sort()
    
    print(len(good_values))
    if good_values:
        print(' '.join(map(str, good_values)))

if __name__ == "__main__":
    solve()
